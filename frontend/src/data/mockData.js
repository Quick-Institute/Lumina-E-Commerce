const mkOrder = (n, placedAt, status, items, opts = {}) => {
    const subtotal = items.reduce((sum, it) => sum + it.price * it.qty, 0);
    const deliveryFee = subtotal >= 5000 ? 0 : 450;
    const timeline = buildTimeline(status, placedAt, opts);
    const cancelledAt = status === "Cancelled" ? opts.cancelledAt : null;
    return {
        id: `o${n}`,
        orderNumber: `#ORD-2026-${String(n).padStart(5, "0")}`,
        customerId: "u1",
        customerName: "John Doe",
        customerEmail: "john.doe@example.com",
        placedAt,
        status,
        items,
        subtotal,
        deliveryFee,
        totalAmount: subtotal + deliveryFee,
        payment: {
            method: "Cash on Delivery",
            status:
                status === "Delivered" ? "Paid" : status === "Cancelled" ? "Cancelled" : opts.paymentStatus || "Pending",
            amount: subtotal + deliveryFee,
            payableAtDoor: status === "Pending" || status === "Processing" || status === "Shipped" ? subtotal + deliveryFee : 0,
        },
        address: opts.address || baseAddress,
        notes: opts.notes || "",
        estimatedDelivery: opts.estimatedDelivery || null,
        timeline,
        cancelledAt,
        cancellationReason: status === "Cancelled" ? opts.cancellationReason || null : null,
    };
};

