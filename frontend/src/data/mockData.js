const buildTimeline = (status, placedAt, extra = {}) => {
    const steps = [];
    const d = new Date(placedAt);
    const at = (dayOffset, time) => {
        const nd = new Date(d);
        nd.setDate(nd.getDate() + dayOffset);
        const [h, m] = time.split(":").map(Number);
        nd.setHours(h, m, 0, 0);
        return nd.toISOString();
    };
    steps.push({
        key: "pending",
        title: "Pending",
        note: "Order placed and awaiting seller confirmation",
        at: at(0, "09:30"),
        done: true
    });
    if (["Processing", "Shipped", "Delivered", "Cancelled"].includes(status)) {
        steps.push({
            key: "processing",
            title: "Processing",
            note: "Seller is preparing your order for dispatch",
            at: at(0, "11:45"),
            done: true
        });
    }
    if (status === "Cancelled") {
        steps.push({
            key: "cancelled",
            title: "Cancelled",
            note: extra.cancelNote || "Order was cancelled by the user",
            at: extra.cancelledAt,
            cancelled: true
        });
        return steps;
    }
    if (["Shipped", "Delivered"].includes(status)) {
        steps.push({
            key: "shipped",
            title: "Shipped",
            note: "Your order has been dispatched for delivery",
            at: at(1, "14:15"),
            done: status === "Shipped"
        });
    }
    if (status === "Delivered") {
        steps.push({
            key: "delivered",
            title: "Delivered",
            note: "Order delivered successfully to your address",
            at: at(3, "10:40"),
            done: true
        });
    }
    return steps;
};

